// Regenerate the vector brand kit; no downloads, packages, builds or archives.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../demo/public/', import.meta.url);
const palette = {
  navy: '#031123', surface: '#0b2037', red: '#ed1939', action: '#c8102e',
  cyan: '#08add6', white: '#f7f9fc', muted: '#adbed0', line: '#29425c',
};
mkdirSync(new URL('branding/', root), { recursive: true });
function save(name, text) { writeFileSync(new URL(name, root), text + '\n', 'utf8'); }
function svg(width, height, label, content) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title"><title id="title">${label}</title>${content}</svg>`;
}
// The isolated headset/ECG reference is the primary mark. No alternate emblems.
const mark = `<g fill="none" stroke-linecap="round" stroke-linejoin="round">
  <path stroke="${palette.cyan}" stroke-width="3.2" d="M25 25C33 10 47 4 60 4S87 10 95 25M48 30H27C18 30 14 35 14 43V59C14 68 19 72 28 72H52M68 30H93C102 30 106 35 106 43V59C106 68 101 72 92 72H68M9 38H7C4 38 3 40 3 44V58C3 62 4 64 7 64H9M111 38H113C116 38 117 40 117 44V58C117 62 116 64 113 64H111"/>
  <path stroke="${palette.red}" stroke-width="3.5" d="M18 52H38L43 46L50 59L58 30L66 76L73 48L80 57L85 49L89 52H102"/>
</g>`;
const font = 'Arial, Helvetica, sans-serif';
function wordmark(x, y, size, color) {
  return `<text x="${x}" y="${y}" fill="${color}" font-family="${font}" font-size="${size}" font-style="italic" font-weight="800" letter-spacing="-2">Vital <tspan fill="${palette.red}">VR</tspan></text>`;
}
const tagline = 'Entrena hoy. Salva vidas mañana.';
save('branding/vital-vr-mark.svg', svg(120, 80, 'Vital VR · visor y pulso', mark));
save('vital-mark.svg', svg(96, 96, 'Vital VR', `<rect width="96" height="96" rx="22" fill="${palette.navy}"/><g transform="translate(6 20) scale(.7)">${mark}</g>`));
for (const light of [false, true]) {
  const text = light ? palette.navy : palette.white;
  const background = light ? palette.white : palette.navy;
  const suffix = light ? '-light' : '';
  save(`branding/vital-vr-lockup${suffix}.svg`, svg(560, 112, 'Vital VR', `<g transform="translate(2 12) scale(1.08)">${mark}</g>${wordmark(153, 86, 86, text)}`));
  const stacked = `<g transform="translate(217 62) scale(3.05)">${mark}</g>${wordmark(149, 419, 126, text)}<text x="400" y="484" text-anchor="middle" fill="${text}" font-family="${font}" font-size="28">${tagline}</text>`;
  save(`branding/vital-vr-logo${suffix}.svg`, svg(800, 560, `Vital VR · ${tagline}`, `<rect width="800" height="560" fill="${background}"/>${stacked}`));
  if (!light) save('branding/vital-vr-logo-transparent.svg', svg(800, 560, `Vital VR · ${tagline}`, stacked));
}
save('branding/vital-vr-social.svg', svg(1200, 630, `Vital VR · ${tagline}`, `<rect width="1200" height="630" fill="${palette.navy}"/><path d="M80 544H1120" stroke="${palette.line}"/><g transform="translate(80 211) scale(2.4)">${mark}</g>${wordmark(427, 335, 142, palette.white)}<text x="433" y="402" fill="${palette.white}" font-family="${font}" font-size="29">${tagline}</text><text x="80" y="587" fill="${palette.muted}" font-family="${font}" font-size="19" letter-spacing="3">SIMULACIÓN DE EMERGENCIAS EN REALIDAD VIRTUAL</text>`));
const icons = {
  immersive: `<rect x="9" y="20" width="46" height="28" rx="9"/><path d="M18 15C23 5 41 5 46 15M5 26V41M59 26V41M19 29H27M37 29H45M27 48L32 42L37 48"/>`,
  training: `<path d="M32 54C26 48 8 36 8 22C8 8 25 7 32 19C39 7 56 8 56 22C56 36 38 48 32 54M5 33H20L25 25L30 41L35 20L41 35H59"/>`,
  readiness: `<circle cx="32" cy="32" r="22"/><circle cx="32" cy="32" r="14"/><path d="M32 4V15M32 49V60M4 32H15M49 32H60"/>`,
  confidence: `<circle cx="26" cy="17" r="11"/><path d="M7 54V47C7 32 36 29 41 39M7 54H28"/><circle cx="45" cy="47" r="12"/><path d="M39 47L43 51L51 42"/>`,
};
for (const [name, paths] of Object.entries(icons)) save(`branding/icon-${name}.svg`, svg(64, 64, name, `<g fill="none" stroke="${palette.red}" stroke-width="2.3" stroke-linecap="round" stroke-linejoin="round">${paths}</g>`));
save('branding/palette.json', JSON.stringify({ name: 'Vital VR', tagline, colors: palette }, null, 2));
save('branding/tokens.css', `/* Generated by tools/Generate-VitalBrand.mjs. */\n:root {\n${Object.entries(palette).map(([key, value]) => `  --brand-${key}: ${value};`).join('\n')}\n  --brand-font: "Segoe UI", Arial, Helvetica, sans-serif;\n}`);
console.log('Vital VR vector brand kit generated in ' + fileURLToPath(new URL('branding/', root)));
